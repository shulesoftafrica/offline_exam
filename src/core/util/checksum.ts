/**
 * SHA-256 and canonical JSON.
 *
 * Checksums are part of the API contract (bundle completeness, answer payload integrity,
 * attachment idempotency), so they must be byte-identical between the browser and the
 * server. `WebCrypto` is used when present; the pure-TS fallback exists because
 * `crypto.subtle` is unavailable on insecure origins (a lab machine reached over plain
 * HTTP) and in some test environments, and a missing digest must never stop an exam.
 */

